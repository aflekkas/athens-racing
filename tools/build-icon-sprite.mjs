// Builds assets/icons/sprite.svg from the vendored Phosphor icons (bold weight, MIT, assets/icons/LICENSE).
// Add an icon: copy <name>-bold.svg from @phosphor-icons/core/assets/bold to assets/icons/<name>.svg and re-run
//   node tools/build-icon-sprite.mjs
// The UI references icons as <svg><use href="assets/icons/sprite.svg#name"/></svg> (src/ui/components.js icon()).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../assets/icons/', import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith('.svg') && f !== 'sprite.svg').sort();
const symbols = files.map((f) => {
  const src = readFileSync(new URL(f, dir), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(src)?.[1] || '0 0 256 256';
  const body = src.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  return `<symbol id="${f.slice(0, -4)}" viewBox="${viewBox}" fill="currentColor">${body}</symbol>`;
});
writeFileSync(new URL('sprite.svg', dir), `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Phosphor Icons (bold), MIT License, see LICENSE. Generated by tools/build-icon-sprite.mjs -->\n${symbols.join('\n')}\n</svg>\n`);
console.log(`sprite.svg: ${symbols.length} icons`);
