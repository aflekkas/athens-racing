// Builds the offline Lucide sprite from the pinned vendored SVGs. See docs/ui-icons.md.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

export function buildSprite() {
  const dir = new URL('../assets/icons/', import.meta.url);
  const files = readdirSync(dir).filter(f => f.endsWith('.svg') && f !== 'sprite.svg').sort();
  const symbols = files.map(f => {
    const src = readFileSync(new URL(f, dir), 'utf8');
    if (!src.includes('@license lucide-static v1.59.0 - ISC')) throw new Error(`Unpinned Lucide icon: ${f}`);
    const body = src.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    return `<symbol id="${f.slice(0, -4)}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide, lucide-static 1.59.0, ISC; see LICENSE (includes Feather attribution). Generated by tools/build-icon-sprite.mjs -->\n${symbols.join('\n')}\n</svg>\n`;
}
if (process.argv[1] === new URL(import.meta.url).pathname) {
  writeFileSync(new URL('../assets/icons/sprite.svg', import.meta.url), buildSprite());
}
