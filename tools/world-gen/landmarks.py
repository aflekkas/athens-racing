#!/usr/bin/env python3
"""Athens landmark placements from OSM: centre, long-axis yaw, size and DEM ground height of each landmark footprint.

`landmarks.py CACHE OUT.json` reads the pinned Attica extract (ways and multipolygon relations by id) and the DEM, and writes
the table `src/athens-landmark-data.js` is generated from (`landmarks.py --js`). Positions are world metres (x east, z south),
the projection the cells use. Nothing here touches a cell: the landmarks are modelled once in `src/athens-landmarks.js`."""
import json,math,sys
from pathlib import Path
import osmium,rasterio,numpy as np
from shapely.geometry import Polygon,MultiPolygon
from shapely.ops import unary_union

LAT0,LON0,MLAT,MLON=37.98,23.73,111320.,87745.27512677578
WAYS={'parthenon':910010406,'erechtheion':910010334,'olympieion':63765671,'hadrian':175107932}
RELATIONS={'parliament':2150086,'zappeion':9919585,'propylaia':12352555,'stadium':19023846}
def world(lat,lon):return ((lon-LON0)*MLON,-(lat-LAT0)*MLAT)

class Collect(osmium.SimpleHandler):
 def __init__(s):super().__init__();s.shapes={}
 def area(s,a):
  oid=a.orig_id()
  for name,wid in WAYS.items():
   if a.from_way() and oid==wid:s.shapes[name]=s._poly(a)
  for name,rid in RELATIONS.items():
   if not a.from_way() and oid==rid:s.shapes[name]=s._poly(a)
 def _poly(s,a):
  parts=[]
  for ring in a.outer_rings():
   pts=[world(n.lat,n.lon) for n in ring]
   if len(pts)>=4:parts.append(Polygon(pts).buffer(0))
  return unary_union(parts)

def footprint(poly):
 """Centre, yaw of the long axis (radians, three.js rotation.y of a local +x axis), length, width, area and the outline."""
 rect=poly.minimum_rotated_rectangle;pts=list(rect.exterior.coords)[:4]
 e=[(pts[(i+1)%4][0]-pts[i][0],pts[(i+1)%4][1]-pts[i][1]) for i in range(2)]
 a,b=(e[0],e[1]) if math.hypot(*e[0])>=math.hypot(*e[1]) else (e[1],e[0])
 yaw=-math.atan2(a[1],a[0]);c=rect.centroid;m=poly.centroid;n=math.hypot(*a)
 # `heavy` is which way along the long axis the footprint's mass lies (+1 toward local +x): the closed end of a horseshoe.
 heavy=1 if ((m.x-c.x)*a[0]+(m.y-c.y)*a[1])/n>0 else -1
 return dict(x=round(c.x,1),z=round(c.y,1),yaw=round(yaw,4),length=round(n,1),width=round(math.hypot(*b),1),area=round(poly.area),heavy=heavy)

def covered_buildings(clean,shape,margin=3,min_height=0):
 """Ids of the cleaned OSM buildings whose centroid lies inside the hull of `shape` (buffered 3 m; a horseshoe's centroid is in its arena): the flat boxes a landmark model replaces."""
 import sqlite3
 from shapely.geometry import Point
 area=shape.convex_hull.buffer(margin);minx,minz,maxx,maxz=area.bounds;db=sqlite3.connect(f'file:{clean}?mode=ro',uri=True);ids=[]
 for identifier,data in db.execute("SELECT id,data FROM objects WHERE kind='building'"):
  c=data.split('"centroid":[',1)
  if len(c)<2:continue
  x,z=map(float,c[1].split(']',1)[0].split(','))
  if minx<=x<=maxx and minz<=z<=maxz and area.contains(Point(x,z)):
   if min_height and max(p['height'] for p in json.loads(data)['parts'])<min_height:continue
   ids.append(identifier)
 db.close();return sorted(ids)

def ground(dem37,dem38,x,z):
 lat=LAT0-z/MLAT;lon=LON0+x/MLON;t,a=(dem37 if lat<38.00013888 else dem38)
 r=(t.bounds.top-lat)*3600-.5;c=(lon-t.bounds.left)*3600-.5;r0=int(math.floor(r));c0=int(math.floor(c));fr=r-r0;fc=c-c0
 return float((a[r0,c0]*(1-fc)+a[r0,c0+1]*fc)*(1-fr)+(a[r0+1,c0]*(1-fc)+a[r0+1,c0+1]*fc)*fr)

def main():
 cache=Path(sys.argv[1]);out=Path(sys.argv[2]);h=Collect()
 h.apply_file(str(cache/'attica.osm.pbf'),locations=True)
 t37=rasterio.open(cache/'attica-n37-e023.tif');t38=rasterio.open(cache/'attica-n38-e023.tif')
 d37=(t37,t37.read(1).astype('float32'));d38=(t38,t38.read(1).astype('float32'))
 table={}
 for name,shape in sorted(h.shapes.items()):
  if shape.is_empty:continue
  big=max(shape.geoms,key=lambda g:g.area) if isinstance(shape,MultiPolygon) else shape
  f=footprint(big);f['y']=round(ground(d37,d38,f['x'],f['z']),1);f['hide']=covered_buildings(cache/'clean.sqlite',shape,*((60,3) if name=='parliament' else (3,0)))
  table[name]=f
 # Lycabettus summit (OSM natural=peak node 835178426) and the chapel of Agios Georgios next to it.
 x,z=world(37.9818701,23.7432387);table['lycabettus']=dict(x=round(x,1),z=round(z,1),y=round(ground(d37,d38,x,z),1))
 out.write_text(json.dumps(table,indent=1,sort_keys=True))
 if len(sys.argv)>4 and sys.argv[3]=='--js':
  header=("// Generated by tools/world-gen/landmarks.py from OSM (footprints) and the DEM (ground heights); do not edit.\n"
          "// World metres: x east, z south, y metres above sea level. yaw turns the local +x axis (the footprint's long axis); heavy is the side of a horseshoe's closed end.\n")
  Path(sys.argv[4]).write_text(header+"export const LANDMARK_SITES=Object.freeze("+json.dumps(table,sort_keys=True,separators=(',',':'))+");\n")
 print(json.dumps(table,sort_keys=True)[:3000])
if __name__=='__main__':main()
