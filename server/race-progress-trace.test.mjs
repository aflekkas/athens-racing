import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createGameCore } from './core.mjs';
import { resolveMap } from './map-definitions.mjs';
import { getMap } from '../src/map-catalog.js';
import { effectiveEvent } from './mp-lifecycle.mjs';
import { roadFrame, courseProgress, courseComplete } from '../src/course.js';
import { MULTIPLAYER_PROTOCOL } from '../src/multiplayer-protocol.js';
const socket = () => ({ readyState: 1, messages: [], send(data) { this.messages.push(JSON.parse(data)); }, close() {} });
for (const reverse of [false, true]) test(`three-client Psychiko trace: ${reverse ? 'reversed' : 'forward'}, overtakes, shortcuts, tow, restore, laps and results`, t => {
  let now = 100000; t.mock.method(Date, 'now', () => now);
  const map = resolveMap(getMap('psychiko'), JSON.parse(readFileSync(new URL('../data/maps/psychiko/map.json', import.meta.url))));
  const def = [...map.definitions.values()].find(e => e.type === 'sprint');
  const event = effectiveEvent(def, { reverse });
  assert.equal(event.dir, reverse ? -1 : 1); assert.equal(event.s0, 0);
  assert.ok(event.sectors.every(cp => Math.abs((cp.s - event.s0) * event.dir - cp.d) < 1e-6));
  const opts = { maps: new Map([['riviera', map], ['psychiko', map]]), defaultMap: 'psychiko', cars: new Set(['mini']), leaderboard: { submit: async () => {} }, countdownMs: 0, raceLimitMs: 2000000 };
  let core = createGameCore(opts);
  const clients = [socket(), socket(), socket()], names = ['Alice', 'Bob', 'Charlie'];
  const send = (ws, message) => core.message(ws, JSON.stringify(message));
  clients.forEach(ws => core.connect(ws, 'test', { protocol: MULTIPLAYER_PROTOCOL }));
  send(clients[0], { type: 'create', mapId: 'psychiko', name: names[0] });
  const code = clients[0].messages.findLast(m => m.type === 'lobby').lobby.code;
  for (let i = 1; i < 3; i++) send(clients[i], { type: 'join', code, name: names[i] });
  if (reverse) send(clients[0], { type: 'options', config: { reverse: true } });
  for (const ws of clients) send(ws, { type: 'ready', ready: true, version: map.track.version });
  send(clients[0], { type: 'start' }); core.tick();
  const lobby = clients[0].messages.findLast(m => m.type === 'lobby').lobby;
  assert.equal(lobby.event.dir, event.dir);
  const ids = clients.map(ws => core.clientData(ws).id), trace = [];
  const pose = (distance, u = 0, epoch = 1, stopped = false) => {
    const s = event.s0 + event.dir * distance, f = roadFrame(map.geometry, s);
    return { s, u, x: f.x - f.tz * u, y: f.y, z: f.z + f.tx * u, yaw: Math.atan2(-f.tx, -f.tz) + (event.dir < 0 ? Math.PI : 0), vLong: stopped ? 0 : 40, vLat: 0, steer: 0, rpm: 3000, gear: 3, sampleTime: now, motionEpoch: epoch };
  };
  const sample = (i, d, u = 0, epoch = 1, stopped = false) => { now += 100; send(clients[i], { type: 'state', raceId: lobby.raceId, generation: lobby.generation, state: pose(d, u, epoch, stopped) }); };
  const drive = (i, a, b, epoch = 1) => { const dir = Math.sign(b - a); for (let d = a; dir * (b - d) > 0; d += dir * Math.min(4, Math.abs(b - d))) sample(i, d, 0, epoch); sample(i, b, 0, epoch); };
  const record = label => {
    now += 250; core.tick();
    const snapshots = clients.map(ws => ws.messages.findLast(m => m.type === 'snapshot'));
    assert.ok(snapshots.every(s => s && JSON.stringify(s.standings) === JSON.stringify(snapshots[0].standings)), 'every client sees the same authoritative order');
    const rows = snapshots[0].standings.map(row => ({ name: names[ids.indexOf(row.id)], progress: row.progress, position: row.position, finish: row.finish }));
    trace.push({ label, rows }); return rows;
  };
  drive(0, 0, 100); drive(1, 0, 90); drive(2, 0, 80);
  assert.equal(record('Alice leads')[0].name, 'Alice');
  drive(1, 90, 120); assert.equal(record('Bob overtakes')[0].name, 'Bob');
  sample(2, 90, 40); now += 3000; sample(2, 400);
  assert.equal(record('Charlie cuts adjacent streets; no rank gain').find(r => r.name === 'Charlie').progress, 80);
  send(clients[2], { type: 'recover', raceId: lobby.raceId, generation: lobby.generation, motionEpoch: 2, s: event.s1 });
  const ack = clients[2].messages.at(-1); assert.equal(ack.type, 'recovered'); assert.ok(Math.abs(ack.s - event.dir * 400) < 1e-6, 'the tow puts him on the nearest road, where he is'); assert.equal(ack.until - now, 250);
  assert.equal(core.clientData(clients[2]).course.validProgress, 80, 'the tow itself granted no progress'); assert.equal(core.clientData(clients[2]).course.reached, 80);
  sample(2, 400, 0, 2, true); const until = ack.until;
  send(clients[2], { type: 'recover', raceId: lobby.raceId, motionEpoch: 3 });
  assert.equal(clients[2].messages.at(-1).until, until, 'repeat does not stack time');
  sample(2, 300, 0, 2); assert.ok(Math.abs(core.clientData(clients[2]).state.s - ack.s) < 1e-6, 'old motion epoch rejected');
  record('Charlie towed onto the road where he is');
  drive(0, 100, 50); const backwards = record('Alice reverses behind Charlie');
  assert.equal(backwards.find(r => r.name === 'Alice').position, 3);
  const before = core.clientData(clients[0]);
  const saved = JSON.parse(JSON.stringify(core.exportState()));
  const sockets = new Map(clients.map(ws => [core.clientData(ws).token, ws]));
  core = createGameCore(opts); core.restore(saved, sockets);
  assert.equal(courseProgress(core.clientData(clients[0]).course), courseProgress(before.course));
  record('Arena restore retains backwards position and epochs');
  drive(0, 50, event.lapLength); assert.equal(core.clientData(clients[0]).finish, null, 'one lap cannot finish a two-lap race');
  record('Alice crosses lap one');
  drive(0, event.lapLength, event.len + 1);
  const winner = core.clientData(clients[0]); assert.ok(winner.finish > 0); assert.equal(courseComplete(winner.course), true);
  record('Alice finishes after covering both laps');
  send(clients[1], { type: 'dnf', raceId: lobby.raceId, reason: 'retired' });
  send(clients[2], { type: 'dnf', raceId: lobby.raceId, reason: 'retired' });
  const results = clients[0].messages.findLast(m => m.type === 'lobby').lobby;
  assert.equal(results.status, 'results'); assert.equal(results.standings[0].id, ids[0]); assert.equal(results.results[0].finish, winner.finish);
  mkdirSync(new URL('../.scratch/recovery-progress/', import.meta.url), { recursive: true });
  writeFileSync(new URL(`../.scratch/recovery-progress/three-client-${event.dir}.json`, import.meta.url), JSON.stringify({ kind: 'production server, real Psychiko geometry, deterministic pose replay (not driven physics)', event, trace }, null, 2));
  t.diagnostic(trace.map(e => `${e.label}: ${e.rows.map(r => `${r.name} ${r.progress.toFixed(1)}m`).join(' > ')}`).join('\n'));
});
